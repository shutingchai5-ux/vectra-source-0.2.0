export function explainStep(step: Step) {
  const known = stepGuides[step.action];
  const profile = known ?? guide("查看本条记录所描述的处理过程。", "保留每次交互的依据，方便核对本轮进展。", "处理本条记录所述事项", "本条记录标记为已完成，实际内容见消息及原始记录。", ["阅读本条消息与已记录的检查结果。", "需要更多细节时，展开原始记录核对；未记录的行为无法据此确认。"], "继续查看后续消息；本条记录未提供具体的后续安排。" );
  const stopped = step.status === "failed" || step.status === "cancelled";
  const current = step.status === "completed" ? profile.completed : step.status === "running" ? `正在${profile.operation}。`
    : step.status === "queued" ? `正在等待${profile.operation}，本步尚未开始。`
    : step.status === "cancelled" ? `本步已取消：${profile.operation}未完成。` : `本步未完成：${profile.operation}未能完成，原因见错误说明。`;
  return { ...profile, known: Boolean(known), current, next: stopped ? "先根据错误或取消提示处理，再按需重新发起任务；本步不会作为成功结果继续交付。" : profile.next,
    processLabel: stopped ? "原定处理方式" : step.status === "completed" ? "本步处理方式" : step.status === "queued" ? "本步计划处理方式" : "本步正在按以下方式处理", nextLabel: stopped ? "你可以怎么做" : "接下来" };
}

export function taskIntroduction(task: Task): string {
  if (task.status === "completed") return "本轮所需内容已完成并交付。下面保留各角色的处理经过，你可以查看统计、分析和签名报告，也可以继续追问。";
  if (task.status === "failed" || task.status === "cancelled") return "本轮处理已停止。下面会保留已完成的步骤和停止位置；部分统计或分析已经产生，也不代表整轮已经交付。";
  const actions = { statistics: "确认路段、时段和指标，再让计算节点在保护输入的协议中完成统计，最后分析证据并交付签名报告", investigation: "查询真实审计记录，区分已确认事实与可能原因，并给出建议和结论边界", verification: "找到当前对话最近的报告，检查签名与所属任务，再说明实际验证结果", explain: "根据已有公开信息解释你的问题，并说明依据与尚不能确定的部分" };
  return `${task.status === "queued" ? "请求已收到，排到本轮后" : "我会"}${actions[task.plan.intent]}。你可以在下方逐步查看各角色的进展。`;
}

export function taskRecovery(code: string): string {
  if (code === "cancelled") return "任务已取消。需要继续时，可以重新发送问题；已保存的历史步骤仍可查阅。";
  if (code === "invalid_statistics") return "请检查路段、时间与指标。时间请按上海时区填写，结束时间不能晚于当前时刻，单次跨度最多 31 天。";
  if (code === "model_unavailable" || code === "empty_model_reply") return "请在模型设置中检查服务地址、模型名称和访问凭据，确认可用后重新发送问题。";
  if (code === "report_missing") return "当前对话尚无可验证的报告。请先完成一次任务并取得签名报告，再发起验证。";
  if (code === "contract_incomplete") return "本轮缺少所需结果，因此没有完成交付。可以查看停止前的步骤，修正问题后重新发起任务。";
  if (code.startsWith("audit_") || code.startsWith("checkpoint_")) return "请先在“证据与审计”中执行完整校验，核对具体问题，再处理本轮任务。";
  return "先查看停止位置与错误说明，处理原因后再重新发起任务；已记录的步骤可作为排查依据。";
}
